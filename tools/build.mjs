/**
 * Build the Tide & Timber client bundle.
 *
 * The plugin is a single, dependency-free browser bundle, so no bundler is
 * needed: this script validates the two palettes and substitutes them into the
 * plain-IIFE template. Run from anywhere:
 *
 *   node dsh-theme-tide/tools/build.mjs
 *
 * Output: ../client.js (committed / shipped with the package).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { LIGHT, DARK, SOURCE, LABEL } from '../src/palette.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');

function fail(message) {
  console.error(`[tide-and-timber] build failed: ${message}`);
  process.exitCode = 1;
  process.exit(1);
}

const lightKeys = Object.keys(LIGHT).sort();
const darkKeys = Object.keys(DARK).sort();
if (lightKeys.length === 0) fail('LIGHT palette is empty');

const missingInDark = lightKeys.filter((key) => !(key in DARK));
const missingInLight = darkKeys.filter((key) => !(key in LIGHT));
if (missingInDark.length || missingInLight.length) {
  fail(
    `palette key mismatch — light-only: [${missingInDark.join(', ')}], dark-only: [${missingInLight.join(', ')}]`,
  );
}
const bad = lightKeys.filter((key) => !key.startsWith('--dsw-alias-'));
if (bad.length) fail(`non-alias token names: [${bad.join(', ')}]`);
const dupes = lightKeys.length !== new Set(lightKeys).size;
if (dupes) fail('duplicate token names');

const template = readFileSync(path.join(root, 'src', 'client.template.js'), 'utf8');
const banner = `/* ${LABEL.en} (${LABEL.zh}) — DSH theme plugin; ${lightKeys.length} --dsw-alias-* tokens per scheme. Generated by tools/build.mjs, do not edit. */\n`;
const bundle = banner +
  template
    .replaceAll('__SOURCE__', SOURCE)
    .replaceAll('__LIGHT__', JSON.stringify(LIGHT, null, 2))
    .replaceAll('__DARK__', JSON.stringify(DARK, null, 2));

if (bundle.includes('__LIGHT__') || bundle.includes('__DARK__') || bundle.includes('__SOURCE__')) {
  fail('template placeholder substitution incomplete');
}
if (!bundle.includes('overrideTokens')) fail('template does not reference overrideTokens');

writeFileSync(path.join(root, 'client.js'), bundle);
console.log(
  `[tide-and-timber] wrote client.js — ${lightKeys.length} tokens, ${(bundle.length / 1024).toFixed(1)} KiB, source=${SOURCE}`,
);
